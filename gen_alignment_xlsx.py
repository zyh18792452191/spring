def merge_col(ws, start_row, end_row, col, value):
    if start_row < end_row:
        ws.merge_cells(start_row=start_row, start_column=col, end_row=end_row, end_column=col)
    c = ws.cell(start_row, col, value)
    c.font = BOLD_FONT; c.alignment = CENTER_ALIGN; c.border = THIN_BORDER

def merge_by_group(ws, data, col_idx, start_row=2):
    """按某列连续相同值分组合并。
    - 当该列值为空时，fill-down到前一个非空值（归入同一分组）
    - 当该列值非空且与前一个值不同时，开始新分组
    """
    # 第一步：fill-down空值
    filled = []
    last_val = None
    for item in data:
        val = item[col_idx] if isinstance(item, (list, tuple)) else item
        if val:
            last_val = val
        filled.append(last_val)

    # 第二步：按连续相同值分组
    groups = []
    if not filled:
        return
    cur_val = filled[0]; cur_start = start_row
    for i in range(1, len(filled)):
        row = start_row + i
        if filled[i] != cur_val:
            groups.append((cur_start, row - 1, cur_val))
            cur_val = filled[i]; cur_start = row
    groups.append((cur_start, start_row + len(filled) - 1, cur_val))

    for s, e, v in groups:
        merge_col(ws, s, e, col_idx + 1, v)

