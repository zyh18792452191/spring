# ============ 样式常量 ============
FONT_NAME = '微软雅黑'
HEADING1_COLOR = RGBColor(0x1F, 0x4E, 0x79)  # 深蓝
TABLE_HEADER_BG = '1F4E79'
TABLE_ALT_BG = 'EBF5FB'

def set_cell_shading(cell, color_hex):
    shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{color_hex}" w:val="clear"/>')
    cell._tc.get_or_add_tcPr().append(shading)

def add_cover_page(doc, title, subtitle):
    doc.add_paragraph()
    doc.add_paragraph()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(title)
    run.font.size = Pt(28)
    run.font.color.rgb = HEADING1_COLOR
    run.font.name = FONT_NAME
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
    run.bold = True
    
    p2 = doc.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run2 = p2.add_run(subtitle)
    run2.font.size = Pt(16)
    run2.font.color.rgb = RGBColor(0x5B, 0x9B, 0xD5)
    run2.font.name = FONT_NAME
    run2._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
    
    doc.add_paragraph()
    
    info_items = [
        ('文档版本', 'V1.0'),
        ('页面路径', '洞察中心 > AI洞察助手 / AI洞察管理'),
        ('最后更新', '2026-07-03'),
    ]
    table = doc.add_table(rows=len(info_items), cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (k, v) in enumerate(info_items):
        cell_k = table.cell(i, 0)
        cell_v = table.cell(i, 1)
        cell_k.text = k
        cell_v.text = v
        for cell in [cell_k, cell_v]:
            for paragraph in cell.paragraphs:
                paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
                for run in paragraph.runs:
                    run.font.size = Pt(11)
                    run.font.name = FONT_NAME
                    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
        set_cell_shading(cell_k, TABLE_HEADER_BG)
        for run in cell_k.paragraphs[0].runs:
            run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            run.bold = True
    
    doc.add_page_break()

def add_heading(doc, text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.name = FONT_NAME
        run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
        if level == 1:
            run.font.color.rgb = HEADING1_COLOR

def add_para(doc, text, bold=False, italic=False, size=10.5):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.font.name = FONT_NAME
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
    run.bold = bold
    run.italic = italic
    p.paragraph_format.line_spacing = Pt(16)
    return p

def add_bullet(doc, text, bold_prefix=None):
    p = doc.add_paragraph(style='List Bullet')
    if bold_prefix:
        run_b = p.add_run(bold_prefix)
        run_b.bold = True
        run_b.font.size = Pt(10.5)
        run_b.font.name = FONT_NAME
        run_b._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
        run_n = p.add_run(text)
        run_n.font.size = Pt(10.5)
        run_n.font.name = FONT_NAME
        run_n._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
    else:
        run = p.add_run(text)
        run.font.size = Pt(10.5)
        run.font.name = FONT_NAME
        run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
    return p

def add_number(doc, text):
    p = doc.add_paragraph(style='List Number')
    run = p.add_run(text)
    run.font.size = Pt(10.5)
    run.font.name = FONT_NAME
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
    return p

def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        cell = table.cell(0, j)
        cell.text = h
        set_cell_shading(cell, TABLE_HEADER_BG)
        for run in cell.paragraphs[0].runs:
            run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            run.font.size = Pt(9)
            run.font.name = FONT_NAME
            run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
            run.bold = True
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.cell(i + 1, j)
            cell.text = str(val)
            if i % 2 == 1:
                set_cell_shading(cell, TABLE_ALT_BG)
            for run in cell.paragraphs[0].runs:
                run.font.size = Pt(9)
                run.font.name = FONT_NAME
                run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_NAME)
    return table

def add_submodule_heading(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
