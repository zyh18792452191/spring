function para(text, opts = {}) {
  children.push(new Paragraph({
    children: [new TextRun({ text, size: 21, font: '微软雅黑', ...opts })],
    spacing: { after: 120 },
    indent: opts.indent ? { firstLine: 420 } : undefined
  }));
}

function bullet(text, level = 0) {
  children.push(new Paragraph({
    children: [new TextRun({ text, size: 21, font: '微软雅黑' })],
    bullet: { level },
    spacing: { after: 80 }
  }));
}

function makeRow(cells, isHeader = false) {
  return new TableRow({
    children: cells.map(text => new TableCell({
      children: [new Paragraph({
        children: [new TextRun({ text, size: 20, font: '微软雅黑', bold: isHeader })],
        spacing: { before: 40, after: 40 }
      })],
      width: { size: Math.floor(10000 / cells.length), type: WidthType.DXA }
    }))
  });
}

function table(headers, rows) {
  children.push(new Table({
    rows: [makeRow(headers, true), ...rows.map(r => makeRow(r))],
    width: { size: 10000, type: WidthType.DXA }
  }));
  children.push(new Paragraph({ spacing: { after: 200 } }));
}

