function heading1(t) { return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing:{before:400,after:200}, children:[new TextRun({text:t,bold:true,size:32,font:'Microsoft YaHei'})] }); }
function heading2(t) { return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing:{before:300,after:150}, children:[new TextRun({text:t,bold:true,size:28,font:'Microsoft YaHei'})] }); }
function heading3(t) { return new Paragraph({ heading: HeadingLevel.HEADING_3, spacing:{before:200,after:100}, children:[new TextRun({text:t,bold:true,size:24,font:'Microsoft YaHei'})] }); }
function para(t,opts={}) { return new Paragraph({ spacing:{after:100,line:360}, indent:opts.indent?{left:360}:undefined, children:[new TextRun({text:t,size:21,font:'Microsoft YaHei',...opts})] }); }
function boldPara(t) { return para(t,{bold:true}); }
function bullet(t,l=0) { return new Paragraph({ spacing:{after:60,line:340}, indent:{left:360+l*360}, children:[new TextRun({text:'\u2022 '+t,size:21,font:'Microsoft YaHei'})] }); }
function emptyLine() { return new Paragraph({ spacing:{after:60}, children:[] }); }

function tbl(h,rows){
  const hc=h.map(x=>new TableCell({shading:{type:ShadingType.SOLID,color:'1F4E79'},children:[new Paragraph({alignment:AlignmentType.CENTER,children:[new TextRun({text:x,bold:true,size:20,font:'Microsoft YaHei',color:'FFFFFF'})]})]}));
  const dr=rows.map((r,i)=>new TableRow({children:r.map(c=>new TableCell({shading:i%2===0?{type:ShadingType.SOLID,color:'F2F7FB'}:undefined,children:[new Paragraph({spacing:{after:40},children:[new TextRun({text:c,size:20,font:'Microsoft YaHei'})]})]}))}));
  return new Table({width:{size:100,type:WidthType.PERCENTAGE},layout:TableLayoutType.FIXED,rows:[new TableRow({children:hc}),...dr]});
}

