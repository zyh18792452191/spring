// ========== 工具函数 ==========
const FONT = `微软雅黑`;
const FONT_EN = "Consolas";

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 400, after: 200 },
    children: [new TextRun({ text, font: FONT, size: 32, bold: true, color: "1a1a2e" })],
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 300, after: 150 },
    children: [new TextRun({ text, font: FONT, size: 28, bold: true, color: "16213e" })],
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 200, after: 100 },
    children: [new TextRun({ text, font: FONT, size: 24, bold: true, color: "0f3460" })],
  });
}
function p(text, opts = {}) {
  const runs = [];
  if (typeof text === "string") {
    runs.push(new TextRun({ text, font: FONT, size: 21, ...opts }));
  } else {
    text.forEach(t => runs.push(new TextRun({ font: FONT, size: 21, ...t })));
  }
  return new Paragraph({ spacing: { after: 80 }, children: runs });
}
function pBold(label, value) {
  return p([
    { text: label, bold: true },
    { text: value }
  ]);
}
function bullet(text, level = 0) {
  return new Paragraph({
    spacing: { after: 60 },
    indent: { left: 360 + level * 360 },
    children: [new TextRun({ text: `• ${text}`, font: FONT, size: 21 })],
  });
}
function note(text) {
  return new Paragraph({
    spacing: { after: 80 },
    indent: { left: 360 },
    children: [new TextRun({ text: `注：${text}`, font: FONT, size: 20, italics: true, color: "666666" })],
  });
}

// ========== 表格 ==========
const BORDER = { style: BorderStyle.SINGLE, size: 1, color: "cccccc" };
const BORDERS = { top: BORDER, bottom: BORDER, left: BORDER, right: BORDER };
const HEADER_BG = "2c3e50";
const ALT_BG = "f8f9fa";

function makeRow(cells, isHeader = false, isAlt = false) {
  return new TableRow({
    children: cells.map(text => {
      const shading = isHeader
        ? { type: ShadingType.SOLID, color: HEADER_BG }
        : isAlt
        ? { type: ShadingType.SOLID, color: ALT_BG }
        : undefined;
      return new TableCell({
        borders: BORDERS,
        shading,
        verticalAlign: VerticalAlign.CENTER,
        children: [new Paragraph({
          spacing: { before: 40, after: 40 },
          children: [new TextRun({
            text: String(text),
            font: FONT,
            size: isHeader ? 20 : 19,
            bold: isHeader,
            color: isHeader ? "ffffff" : "333333",
          })],
        })],
      });
    }),
  });
}

function makeTable(headers, rows, widths) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      makeRow(headers, true),
      ...rows.map((r, i) => makeRow(r, false, i % 2 === 1)),
    ],
  });
}

