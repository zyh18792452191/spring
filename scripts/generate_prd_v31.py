    if os.path.exists(img_path):
        doc.add_picture(img_path, width=Inches(width_inches))
        last = doc.paragraphs[-1] if doc.paragraphs else None
        # Center the image
        for p in doc.paragraphs:
            if p._element.getparent() == doc.element.body:
                pass
        # Actually the picture is in a run; let's set alignment on the paragraph
        # The picture was added to the last paragraph
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    else:
        add_para(doc, f'[图片 {image_name} 未找到]')


