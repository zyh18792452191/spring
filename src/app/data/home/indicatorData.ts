// - 凡是带有"较上月同期"的指标（主指标子指标含"较上月同期"或子指标有较月同期值），均支持日/月维度（both）
// - both型指标：日维度看月初至T日累计值，月维度看整月值；主指标有较月同期列
// - 纯月指标(monthly)：只在月维度查看，无较月同期
// - 纯日指标(daily)：只在日维度查看，无较月同期
// - 变化量型子指标（较上月同期、较上月改善、环比、同比等）本身无额外较月同期
// - 维度值型子指标：both型指标下的才有较月同期值，其余没有

import type { IndicatorModule, MainIndicator, SubIndicator, AvailableTimeMode, CardDisplayMode } from './types';

// ===== 子指标ID生成辅助 =====
let _subId = 0;
function subId(): string { return `sub-${++_subId}`; }

// ===== 子指标构造辅助 =====
// dimSub(维度值型): 有独立数值含义
//   - 日累计型指标下：交叉表格中 值列 + 较上月同期列
//   - 非日累计型指标下：交叉表格中只有值列
//   - 卡片展示：标签名: 值 单位（如"超限率: -40.49%"）
function dimSub(name: string, unit: string, value: number, momChange?: string, dir?: 'up'|'down'|'flat', positive?: boolean, dailyValue?: number): SubIndicator {
  const base = momChange !== undefined && dir !== undefined && positive !== undefined
    ? { id: subId(), name, unit, value, changeValue: momChange, changeDirection: dir, isPositive: positive }
    : { id: subId(), name, unit, value };
  if (dailyValue !== undefined) return { ...base, dailyValue };
  return base;
}
// chgSub(变化量型): 本身就是变化量（较上月同期、较上月改善、环比、同比等），无额外较上月同期
//   - 交叉表格中：只有值列，无较上月同期列
//   - 卡片展示：标签名: 值 单位（如"较上月同期: -0.10%"、"较上月改善: 0.16pp"）
function chgSub(name: string, unit: string, value: number, dailyValue?: number): SubIndicator {
  if (dailyValue !== undefined) return { id: subId(), name, unit, value, dailyValue };
  return { id: subId(), name, unit, value };
}

function makeMain(id: string, name: string, unit: string, value: number, changeVal: string | undefined, dir: 'up'|'down'|'flat', positive: boolean, timeMode: AvailableTimeMode, subs: SubIndicator[], displayMode: CardDisplayMode, source: string, caliber?: string, dailyValue?: number): MainIndicator {
  const base: MainIndicator = { id, name, unit, value, changeValue: changeVal, changeDirection: dir, isPositive: positive, availableTimeMode: timeMode, subIndicators: subs, cardDisplayMode: displayMode, source, caliber };
  if (dailyValue !== undefined) return { ...base, dailyValue };
  return base;
}

